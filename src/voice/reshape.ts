/**
 * Reshapes an adult voice into a child's: the same three changes as Praat's
 * "Change gender" (Boersma & Weenink), written in TypeScript so the build
 * script and every device produce identical clips.
 *
 * 1. Formants up (a shorter vocal tract): band-limited resampling, which
 *    raises every frequency by `formant` and shortens the sound.
 * 2. Pitch to the target median, with the range widened (livelier): TD-PSOLA,
 *    which changes pitch without moving the formants.
 * 3. Duration: PSOLA restores the length and applies `duration`.
 *
 * Since ADR 0011 the app's child voices are generated by the model itself and
 * are not reshaped; since ADR 0012 they get one even formant lift
 * (envelopeLift.ts), then `finish` (trim, fades, loudness).
 * `reshape` stays for the listening benchmarks that compare against it.
 */

import { normaliseLoudness } from "./loudness";

export interface ReshapeSettings {
  /** Formant shift ratio, e.g. 1.16. */
  readonly formant: number;
  /** New median pitch in Hz, e.g. 285. */
  readonly median: number;
  /** Pitch range factor around the median, e.g. 1.3 (1 = unchanged). */
  readonly range: number;
  /** Duration factor, e.g. 1.06 (slightly slower). */
  readonly duration: number;
}

const FLOOR = 75;
const CEILING = 600;
const STEP_SECONDS = 0.01;

/** Pitch (Hz) every 10 ms by normalised autocorrelation; 0 where unvoiced. */
export function trackPitch(x: Float32Array, sr: number): Float32Array {
  const step = Math.round(sr * STEP_SECONDS);
  const win = Math.round((sr / FLOOR) * 2.5);
  const minLag = Math.floor(sr / CEILING);
  const maxLag = Math.ceil(sr / FLOOR);
  const frames = Math.max(1, Math.floor(x.length / step));
  const f0 = new Float32Array(frames);
  let peak = 0;
  for (let i = 0; i < x.length; i++) peak = Math.max(peak, Math.abs(x[i]!));
  const silence = (peak * 0.04) ** 2;
  for (let f = 0; f < frames; f++) {
    const start = f * step - (win >> 1);
    if (start < 0 || start + win + maxLag >= x.length) continue;
    let energy = 0;
    for (let i = 0; i < win; i++) energy += x[start + i]! ** 2;
    if (energy / win < silence) continue;
    let best = 0;
    let bestLag = 0;
    const scores = new Float32Array(maxLag + 2);
    for (let lag = minLag; lag <= maxLag; lag++) {
      let sum = 0;
      let e2 = 0;
      for (let i = 0; i < win; i++) {
        const b = x[start + i + lag]!;
        sum += x[start + i]! * b;
        e2 += b * b;
      }
      const r = sum / Math.sqrt(energy * e2 + 1e-12);
      scores[lag] = r;
      // A slight preference for shorter lags avoids octave-down errors.
      const score = r * (1 - 0.0005 * (lag - minLag));
      if (score > best) {
        best = score;
        bestLag = lag;
      }
    }
    if (best > 0.5 && bestLag > 0) {
      // Parabolic interpolation finds the period between whole samples, so
      // the pitch doesn't move in steps (steps are heard as roughness).
      let lag = bestLag;
      if (bestLag > minLag && bestLag < maxLag) {
        const a = scores[bestLag - 1]!;
        const b = scores[bestLag]!;
        const c = scores[bestLag + 1]!;
        const d = a - 2 * b + c;
        if (d < 0) lag = bestLag + Math.max(-0.5, Math.min(0.5, (0.5 * (a - c)) / d));
      }
      f0[f] = sr / lag;
    }
  }
  // Median of 5 frames removes single-frame jumps; very short voiced runs are noise.
  const smooth = new Float32Array(frames);
  for (let f = 0; f < frames; f++) {
    if (f0[f] === 0) continue;
    const near: number[] = [];
    for (let k = f - 2; k <= f + 2; k++) if (k >= 0 && k < frames && f0[k]! > 0) near.push(f0[k]!);
    near.sort((a, b) => a - b);
    smooth[f] = near[near.length >> 1]!;
  }
  for (let f = 0; f < frames;) {
    if (smooth[f] === 0) {
      f++;
      continue;
    }
    let end = f;
    while (end < frames && smooth[end]! > 0) end++;
    if (end - f < 3) smooth.fill(0, f, end);
    f = end;
  }
  // Then a gentle 50 ms average (in octaves) within each voiced stretch: the
  // melody of speech stays, the frame-to-frame wobble of measuring it goes.
  const out = new Float32Array(frames);
  const weights = [0.25, 0.75, 1, 0.75, 0.25];
  for (let f = 0; f < frames; f++) {
    if (smooth[f] === 0) continue;
    let sum = 0;
    let total = 0;
    for (let k = -2; k <= 2; k++) {
      const v = smooth[f + k] ?? 0;
      if (v <= 0) continue;
      sum += weights[k + 2]! * Math.log2(v);
      total += weights[k + 2]!;
    }
    out[f] = 2 ** (sum / total);
  }
  return out;
}

/** The pitch at a moment between frames, by linear interpolation (0 when unvoiced). */
function pitchAt(f0: Float32Array, frame: number): number {
  const i = Math.max(0, Math.min(f0.length - 1, Math.floor(frame)));
  const a = f0[i] ?? 0;
  const b = f0[Math.min(f0.length - 1, i + 1)] ?? 0;
  if (a <= 0) return 0;
  if (b <= 0) return a;
  const q = Math.max(0, Math.min(1, frame - i));
  return a + (b - a) * q;
}

function median(values: Float32Array): number {
  const voiced = Array.from(values).filter((v) => v > 0);
  if (voiced.length === 0) return 0;
  voiced.sort((a, b) => a - b);
  return voiced[voiced.length >> 1]!;
}

/** Reads the sound faster by `ratio` with a windowed-sinc low-pass, so nothing aliases. */
export function resample(x: Float32Array, ratio: number, taps = 24): Float32Array {
  const out = new Float32Array(Math.floor(x.length / ratio));
  const cutoff = Math.min(1, 1 / ratio);
  for (let n = 0; n < out.length; n++) {
    const t = n * ratio;
    const centre = Math.floor(t);
    let sum = 0;
    let norm = 0;
    for (let k = centre - taps + 1; k <= centre + taps; k++) {
      if (k < 0 || k >= x.length) continue;
      const d = t - k;
      const arg = Math.PI * d * cutoff;
      const sinc = d === 0 ? 1 : Math.sin(arg) / arg;
      const w = 0.5 + 0.5 * Math.cos((Math.PI * d) / taps);
      const h = sinc * w;
      sum += x[k]! * h;
      norm += h;
    }
    out[n] = norm !== 0 ? sum / norm : 0;
  }
  return out;
}

/**
 * Analysis marks: one per pitch period where voiced, every 10 ms where not.
 * Voiced marks sit on the waveform peak of one consistent polarity per voiced
 * stretch, refined by matching each period to the previous one, so the grains
 * line up cleanly (jittery marks are what make PSOLA sound rough).
 */
function pitchMarks(
  y: Float32Array,
  sr: number,
  f0: Float32Array,
  frameSeconds: number,
  pitchScale: number,
) {
  const marks: { at: number; period: number; voiced: boolean }[] = [];
  const f0At = (i: number) => pitchAt(f0, i / sr / frameSeconds) * pitchScale;
  let i = 0;
  while (i < y.length) {
    if (f0At(i) <= 0) {
      const period = Math.round(sr * 0.01);
      marks.push({ at: i, period, voiced: false });
      i += period;
      continue;
    }
    // One voiced stretch: find its end and its stronger polarity.
    let end = i;
    while (end < y.length && f0At(end) > 0) end++;
    let hi = 0;
    let lo = 0;
    for (let k = i; k < end; k++) {
      hi = Math.max(hi, y[k]!);
      lo = Math.min(lo, y[k]!);
    }
    const sign = hi >= -lo ? 1 : -1;
    // First mark: the strongest peak within the first period.
    let period = sr / f0At(i);
    let at = i;
    for (let k = i; k < Math.min(end, i + period); k++) if (sign * y[k]! > sign * y[at]!) at = k;
    while (at < end) {
      marks.push({ at, period, voiced: true });
      const hz = f0At(at);
      if (hz <= 0) break;
      period = sr / hz;
      const guess = Math.round(at + period);
      const reach = Math.floor(period * 0.2);
      // Best match of the next period against this one (waveform similarity),
      // nudged towards the peak, keeps marks evenly on the same point.
      const len = Math.round(period);
      let best = guess;
      let bestScore = -Infinity;
      const scoreAt = new Map<number, number>();
      const base = Math.round(at);
      for (let c = guess - reach; c <= guess + reach; c++) {
        if (c + len >= y.length || c < 0) continue;
        let score = 0;
        for (let k = -len >> 1; k < len >> 1; k++) {
          const a = y[base + k] ?? 0;
          score += a * (y[c + k] ?? 0);
        }
        score += sign * y[c]! * len * 0.05;
        scoreAt.set(c, score);
        if (score > bestScore) {
          bestScore = score;
          best = c;
        }
      }
      // Between whole samples: the top of a parabola through the best three.
      const sa = scoreAt.get(best - 1);
      const sc = scoreAt.get(best + 1);
      let frac = 0;
      if (sa !== undefined && sc !== undefined) {
        const d = sa - 2 * bestScore + sc;
        if (d < 0) frac = Math.max(-0.5, Math.min(0.5, (0.5 * (sa - sc)) / d));
      }
      at = best + frac;
    }
    i = Math.max(end, Math.round((marks.at(-1)?.at ?? i) + period));
  }
  return marks;
}

/** The signal between samples (Catmull-Rom cubic). */
function sampleAt(y: Float32Array, at: number): number {
  const i = Math.floor(at);
  if (i < 1 || i + 2 >= y.length) return y[Math.round(at)] ?? 0;
  const q = at - i;
  const p0 = y[i - 1]!;
  const p1 = y[i]!;
  const p2 = y[i + 1]!;
  const p3 = y[i + 2]!;
  return (
    p1 + 0.5 * q * (p2 - p0 + q * (2 * p0 - 5 * p1 + 4 * p2 - p3 + q * (3 * (p1 - p2) + p3 - p0)))
  );
}

/** Changes pitch and length with TD-PSOLA (formants stay put). */
function psola(
  y: Float32Array,
  sr: number,
  marks: ReturnType<typeof pitchMarks>,
  newPitch: (analysisSample: number) => number,
  stretch: number,
): Float32Array {
  const out = new Float32Array(Math.ceil(y.length * stretch) + sr);
  let t = 0;
  let m = 0;
  const addGrain = (centre: number, from: number, half: number, gain: number) => {
    // Grains are placed between whole samples (by cubic interpolation), so
    // periods are exactly as long as they should be: rounding them to whole
    // samples is itself a wobble the ear hears as roughness.
    for (let dst = Math.ceil(centre - half); dst <= Math.floor(centre + half); dst++) {
      const k = dst - centre;
      if (dst < 0 || dst >= out.length) continue;
      const w = 0.5 + 0.5 * Math.cos((Math.PI * k) / (half + 1));
      out[dst]! += sampleAt(y, from + k) * w * gain;
    }
  };
  while (t < out.length - sr && marks.length > 0) {
    const ta = t / stretch;
    // The two analysis marks either side of where we are.
    while (m + 1 < marks.length && marks[m + 1]!.at <= ta) m++;
    const a = marks[m]!;
    const b = marks[Math.min(marks.length - 1, m + 1)]!;
    const q = b.at > a.at ? Math.max(0, Math.min(1, (ta - a.at) / (b.at - a.at))) : 0;
    const near = q < 0.5 ? a : b;
    if (!a.voiced || !b.voiced) {
      // Breath and hiss have no pitch: take the grain from exactly where we
      // are. Repeating the same 10 ms of hiss (as marks would) makes a buzz.
      const half = Math.round(near.period);
      addGrain(t, ta, half, 1);
      t += near.period;
      continue;
    }
    // The new pitch is read where we are, so periods change smoothly.
    const hz = newPitch(ta) || newPitch(near.at);
    const period = a.period + (b.period - a.period) * q;
    const outPeriod = hz > 0 ? sr / hz : period;
    // Grains span two of the shorter period: raising the pitch then never
    // smears one pulse into the next, and lowering it leaves no gaps.
    const half = Math.round(Math.min(period, outPeriod));
    const gain = outPeriod > period ? Math.sqrt(Math.min(2, outPeriod / period)) : 1;
    // Blend the two neighbouring periods by how far between them we are, so
    // the voice changes smoothly from period to period. Taking only the
    // nearest one repeats some periods and skips others, a pattern heard as
    // a rough, choppy flutter when the pitch is raised a lot.
    if (q > 0.02) addGrain(t, b.at, half, gain * q);
    if (q < 0.98) addGrain(t, a.at, half, gain * (1 - q));
    t += outPeriod;
  }
  return out.subarray(0, Math.ceil(y.length * stretch));
}

export function reshape(x: Float32Array, sr: number, s: ReshapeSettings): Float32Array {
  const f0 = trackPitch(x, sr);
  const oldMedian = median(f0);
  const y = resample(x, s.formant);
  const frame = STEP_SECONDS / s.formant; // the analysis frames shrink with the sound
  // Resampling raised the pitch by `formant` too, so the marks use the raised pitch.
  const marks = pitchMarks(y, sr, f0, frame, s.formant);
  const scaledMedian = oldMedian * s.formant;
  const newPitch = (at: number) => {
    const hz = pitchAt(f0, at / sr / frame) * s.formant;
    if (hz <= 0 || scaledMedian <= 0) return 0;
    // Move to the new median, then widen the range around it (in octaves).
    return s.median * Math.pow(hz / scaledMedian, s.range);
  };
  return psola(y, sr, marks, newPitch, s.formant * s.duration);
}

/** Trims silence at both ends (keeping a short natural edge), fades, and sets the loudness. */
export function finish(x: Float32Array, sr: number): Float32Array {
  let peak = 0;
  for (let i = 0; i < x.length; i++) peak = Math.max(peak, Math.abs(x[i]!));
  if (peak === 0) return x;
  const threshold = peak * 0.02;
  let first = 0;
  let last = x.length - 1;
  while (first < x.length && Math.abs(x[first]!) <= threshold) first++;
  while (last > first && Math.abs(x[last]!) <= threshold) last--;
  const pad = Math.round(0.03 * sr);
  const y = x.slice(Math.max(0, first - pad), Math.min(x.length, last + pad + 1));
  const fade = Math.round(0.008 * sr);
  if (y.length > 2 * fade) {
    for (let i = 0; i < fade; i++) {
      y[i]! *= i / fade;
      y[y.length - 1 - i]! *= i / fade;
    }
  }
  // Same loudness for every clip (not the same peak), with a safe peak.
  normaliseLoudness(y, sr);
  return y;
}
