"""Child-voice control system for Kokoro (prototype).

A child voice is generated by Kokoro's own neural decoder. Nothing is
pitch-shifted or filtered afterwards. Two edits make it young:

1. Timbre. The voice's style vector (decoder half) is moved along directions
   learned from Kokoro's 54 voices:
   - vt: vocal-tract size (formant height). Brightness is held, so a smaller
     vocal tract does not also mean a harsher "s".
   - bright: spectral brightness on its own, as a separate knob.
2. Prosody. The predicted pitch curve is edited inside the graph (median and
   range), and Kokoro's own speed input sets the speaking rate.

Each profile is calibrated by measurement: the timbre move is searched until
the measured formant ratio (against the untouched source, same text and timing)
reaches the target. A male and a female source therefore get different
settings for the same target.
"""
from dataclasses import asdict, dataclass, field

import numpy as np

import kv
import measures as M

V = {k: v.reshape(-1, 256) for k, v in kv.VOICES.items()}
VT = np.load(kv.os.path.join(kv.HERE, "vt_dir_flat.npy"))  # +1 log formant scale, brightness held
BRIGHT = np.load(kv.os.path.join(kv.HERE, "bright_dir.npy"))
BRIGHT_STEP = BRIGHT / (BRIGHT @ BRIGHT)  # +1 log spectral centroid
CAL_ITEMS = ["2-conv-1", "2-conv-2", "3-expr-1", "4-narr-01", "1-short-1"]

# Approximate targets by age, relative to an adult woman's voice, from
# published child acoustics (formants and F0 fall steadily from 5 to 13).
# Starting points only: listening sets the final values.
AGE = {
    7: dict(formant=1.20, f0=275),
    8: dict(formant=1.18, f0=268),
    9: dict(formant=1.15, f0=262),
    10: dict(formant=1.13, f0=255),
    11: dict(formant=1.11, f0=248),
    12: dict(formant=1.09, f0=240),
}
BOY_FORMANT = 0.95  # boys' formants sit a few percent below girls' of the same age
BOY_F0 = 0.93
WOMAN_OVER_MAN = 1.16  # measured here: Kokoro's male timbres sit ~14% below af_heart


@dataclass
class Profile:
    name: str
    timbre: str  # Kokoro voice whose timbre is the starting point
    prosody: str  # Kokoro voice whose delivery (intonation, timing) is used
    age: int = 9
    boy: bool = False
    f0_range: float = 1.10  # >1 livelier intonation
    speed: float = 0.90  # Kokoro's default is too quick for a child or a narrator
    bright: float = 0.0  # +0.1 = about 10% brighter
    # filled by calibrate()
    vt_gain: float = 0.0
    f0_scale: float = 1.0
    f0_ref: float = 200.0
    measured: dict = field(default_factory=dict)

    def target(self):
        a = AGE[self.age]
        formant = a["formant"] * (BOY_FORMANT if self.boy else 1.0)
        if self.timbre[1] == "m":  # male source: also undo the adult sex difference
            formant *= WOMAN_OVER_MAN
        return formant, a["f0"] * (BOY_F0 if self.boy else 1.0)


def table(p: Profile, vt_gain=None):
    t = kv.mix(p.timbre, p.prosody).copy()
    t[:, :128] += np.log(1 + (p.vt_gain if vt_gain is None else vt_gain)) * VT
    t[:, :128] += np.log(1 + p.bright) * BRIGHT_STEP
    return t


def _measured_formant(p, gain, refs):
    t = table(p, gain)
    rs = [M.vt_aligned(kv.say(kv.ITEMS[i]["tokens"], t, speed=p.speed)[0], refs[i], ceiling=6000.0) for i in CAL_ITEMS]
    return float(np.median([r["vt"] for r in rs]))


def calibrate(p: Profile) -> Profile:
    formant, f0 = p.target()
    raw = kv.mix(p.timbre, p.prosody)
    refs = {i: kv.say(kv.ITEMS[i]["tokens"], raw, speed=p.speed)[0] for i in CAL_ITEMS}
    # bisection on the timbre move until the measured formant ratio hits target
    lo, hi = 0.0, 0.8
    for _ in range(7):
        mid = (lo + hi) / 2
        if _measured_formant(p, mid, refs) < formant:
            lo = mid
        else:
            hi = mid
    p.vt_gain = (lo + hi) / 2
    fs = []
    t = table(p)
    for i in CAL_ITEMS:
        _, c = kv.say(kv.ITEMS[i]["tokens"], t, speed=p.speed)
        fs += list(c[c > 40])
    p.f0_ref = float(np.median(fs))
    p.f0_scale = f0 / p.f0_ref
    p.measured = {"target_formant_ratio": formant, "achieved_formant_ratio": _measured_formant(p, p.vt_gain, refs), "target_f0": f0}
    return p


def say(p: Profile, tokens):
    x, _ = kv.say(tokens, table(p), f0_scale=p.f0_scale, f0_range=p.f0_range, f0_ref=p.f0_ref, speed=p.speed)
    return x


def export_style(p: Profile):
    """The finished voice as the app would ship it: one (510, 256) style table
    plus three numbers for the pitch inputs. Same size as any Kokoro voice."""
    return table(p).astype(np.float32), {"f0_scale": p.f0_scale, "f0_range": p.f0_range, "f0_ref": p.f0_ref, "speed": p.speed}


def describe(p: Profile):
    d = asdict(p)
    d["target"] = p.target()
    return d
