// Renders the voice packs with the same engine devices use (src/voice), so
// clips made on a device match the built-in ones exactly.
//
//   npm run voices:texts      list every built-in phrase
//   npm run voices:render     render new clips for both voices, then pack them
//
// Needs ffmpeg on PATH (to make the MP3 clips). Clips are cached by phrase in
// scripts/voices/.cache, so only new or changed phrases are rendered.
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import * as ort from "onnxruntime-node";
import { VOICE_PACK_IDS, type VoicePackId } from "../../src/core/voicePack";
import { renderChildVoice, VOICE_VERSION } from "../../src/voice/childVoices";
import type { Lexicon } from "../../src/voice/g2p";
import { SAMPLE_RATE } from "../../src/voice/kokoro";
import { LEXICON, MODEL_PARTS, voiceTablePath } from "../../src/voice/voiceModel";

const root = new URL("../../", import.meta.url);
const at = (path: string) => new URL(path, root);
const texts = JSON.parse(readFileSync(at("scripts/voices/texts.json"), "utf8")) as {
  key: string;
  text: string;
}[];
const cacheDir = (id: VoicePackId) => at(`scripts/voices/.cache/${VOICE_VERSION}/${id}/`);
const clipFile = (id: VoicePackId, text: string) =>
  new URL(createHash("sha1").update(text).digest("hex").slice(0, 16) + ".mp3", cacheDir(id));

function mp3(samples: Float32Array): Buffer {
  const pcm = Buffer.alloc(samples.length * 2);
  for (let i = 0; i < samples.length; i++)
    pcm.writeInt16LE(Math.max(-32768, Math.min(32767, Math.round(samples[i]! * 32767))), i * 2);
  const result = spawnSync(
    "ffmpeg",
    [
      "-v",
      "error",
      "-f",
      "s16le",
      "-ar",
      String(SAMPLE_RATE),
      "-ac",
      "1",
      "-i",
      "pipe:0",
      "-b:a",
      "48k",
      "-write_xing",
      "0",
      "-id3v2_version",
      "0",
      "-f",
      "mp3",
      "pipe:1",
    ],
    { input: pcm, maxBuffer: 64 * 1024 * 1024 },
  );
  if (result.status !== 0) throw new Error(`ffmpeg failed: ${result.stderr}`);
  return result.stdout;
}

async function renderClips(id: VoicePackId) {
  const model = Buffer.concat(MODEL_PARTS.map((part) => readFileSync(at(`public/${part.path}`))));
  const session = await ort.InferenceSession.create(model, { intraOpNumThreads: 1 });
  const table = readFileSync(at(`public/${voiceTablePath(id)}`));
  const voice = new Float32Array(table.buffer, table.byteOffset, table.byteLength / 4);
  const lexicon = JSON.parse(readFileSync(at(`public/${LEXICON.path}`), "utf8")) as Lexicon;
  const run = async (tokens: BigInt64Array, style: Float32Array) => {
    const out = await session.run({
      tokens: new ort.Tensor("int64", tokens, [1, tokens.length]),
      style: new ort.Tensor("float32", style, [1, 256]),
      speed: new ort.Tensor("float32", new Float32Array([1]), [1]),
    });
    return out.audio!.data as Float32Array;
  };
  mkdirSync(cacheDir(id), { recursive: true });
  let made = 0;
  for (const [n, item] of texts.entries()) {
    const file = clipFile(id, item.text);
    if (!existsSync(file)) {
      writeFileSync(file, mp3(await renderChildVoice(run, voice, lexicon, id, item.text)));
      made++;
    }
    if (n % 100 === 0) console.log(`${id}: ${n}/${texts.length}`);
  }
  console.log(`${id}: ${texts.length} clips (${made} new)`);
}

function pack() {
  const out = at("public/voices/");
  mkdirSync(out, { recursive: true });
  const manifest: Record<string, { audio: string; index: string; bytes: number }> = {};
  for (const id of VOICE_PACK_IDS) {
    const parts: Buffer[] = [];
    const index: Record<string, [number, number]> = {};
    let offset = 0;
    for (const item of texts) {
      const data = readFileSync(clipFile(id, item.text));
      index[item.key] = [offset, data.length];
      parts.push(data);
      offset += data.length;
    }
    const blob = Buffer.concat(parts);
    const digest = createHash("sha1").update(blob).digest("hex").slice(0, 10);
    for (const old of readdirSync(out)) if (old.startsWith(`${id}-`)) rmSync(new URL(old, out));
    writeFileSync(new URL(`${id}-${digest}.mp3`, out), blob);
    writeFileSync(new URL(`${id}-${digest}.json`, out), JSON.stringify(index) + "\n");
    manifest[id] = {
      audio: `voices/${id}-${digest}.mp3`,
      index: `voices/${id}-${digest}.json`,
      bytes: blob.length,
    };
    console.log(`${id}: ${(blob.length / 1e6).toFixed(1)} MB`);
  }
  const generated = at("src/core/voicePacks.generated.ts");
  writeFileSync(
    generated,
    `// Generated by scripts/voices/render.ts. Do not edit.\nimport type { VoicePackId } from "./voicePack";\n\n` +
      `export const VOICE_PACK_FILES: Readonly<Record<VoicePackId, { audio: string; index: string; bytes: number }>> = ${JSON.stringify(manifest, null, 2)};\n`,
  );
  spawnSync("npx", ["prettier", "--write", generated.pathname], { stdio: "inherit" });
}

const [command, only] = process.argv.slice(2);
if (command === "clips") {
  for (const id of VOICE_PACK_IDS) if (!only || only === id) await renderClips(id);
} else if (command === "pack") {
  pack();
} else {
  for (const id of VOICE_PACK_IDS) await renderClips(id);
  pack();
}
